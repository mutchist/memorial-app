"""Convert YouTube .sbv caption files into SQL: one tape entity + its cues.

Usage:  python import_sbv.py LANG OUT.sql TAPE1.sbv TAPE2.sbv ...
Files are taken in the order given as tape 1, 2, 3 ...
Re-running replaces that language's track for each tape; other languages
and all tags (mentions) are untouched.
"""
import re, sys
from pathlib import Path

TIME = re.compile(r'^(\d+):(\d{2}):(\d{2}(?:\.\d+)?),(\d+):(\d{2}):(\d{2}(?:\.\d+)?)$')

def secs(h, m, s): return int(h) * 3600 + int(m) * 60 + float(s)
def q(s): return "'" + s.replace("'", "''") + "'"

def parse(path):
    cues, cur = [], None
    for raw in Path(path).read_text(encoding='utf-8-sig').splitlines():
        line = raw.strip()
        m = TIME.match(line)
        if m:
            cur = [secs(*m.groups()[:3]), secs(*m.groups()[3:]), []]
            cues.append(cur)
        elif line and cur is not None:
            cur[2].append(line)
    out = []
    for start, end, lines in cues:
        text = ' '.join(lines).strip()
        if not text:
            continue
        if end <= start:            # guard against zero-length cues
            end = start + 0.5
        out.append((start, end, text))
    return out

def main():
    lang, out_path, files = sys.argv[1], sys.argv[2], sys.argv[3:]
    sql = ['-- Generated by tools/import_sbv.py. Do not edit by hand.',
           'begin;']
    for n, f in enumerate(files, 1):
        cues = parse(f)
        dur = round(cues[-1][1] + 5, 2)
        sql.append(f'\n-- Tape {n}: {Path(f).name}, {len(cues)} cues')
        sql.append("insert into entities (type, slug, name, attrs) values "
                   f"('tape', 'tape-{n}', 'Tape {n}', "
                   f"'{{\"number\": {n}, \"youtube_id\": null, \"duration_sec\": {dur}}}') "
                   "on conflict (slug) do nothing;")
        sql.append(f"delete from cues where lang = '{lang}' and tape_id = "
                   f"(select id from entities where slug = 'tape-{n}');")
        sql.append("insert into cues (tape_id, lang, seq, start_sec, end_sec, text)\n"
                   f"select t.id, '{lang}', v.seq, v.s, v.e, v.x from entities t, (values\n"
                   + ',\n'.join(f'  ({i}, {s:.3f}, {e:.3f}, {q(x)})' for i, (s, e, x) in enumerate(cues, 1))
                   + f") v(seq, s, e, x)\nwhere t.slug = 'tape-{n}';")
    sql.append('commit;')
    Path(out_path).write_text('\n'.join(sql) + '\n', encoding='utf-8')
    print(f'wrote {out_path}')

if __name__ == '__main__':
    main()

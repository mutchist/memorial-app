"""Combine schema.sql, storage.sql, tapes.sql and seed.sql into supabase-setup.sql, one file
to paste into the Supabase SQL editor of a NEW, empty project.

This is a one-time import. After it, the Supabase database is the source of
truth and changes are made in the admin. Do not run it against a project
that already has data: it would fail on the existing tables.

Usage:  python build_setup.py
"""
from pathlib import Path

DM = Path(__file__).resolve().parents[1]
PARTS = ['schema.sql', 'storage.sql', 'tapes.sql', 'seed.sql', 'updates/2026-11-08-rosa-example.sql']
OUT = DM / 'supabase-setup.sql'

with OUT.open('w', encoding='utf-8', newline='\n') as out:
    out.write('-- Generated by tools/build_setup.py: ' + ' + '.join(PARTS) + '\n')
    out.write('-- Paste into the SQL editor of a new Supabase project and press Run.\n\n')
    for name in PARTS:
        out.write(f'\n-- ===================== {name} =====================\n')
        out.write((DM / name).read_text(encoding='utf-8'))
print('wrote', OUT)
